"use strict";

/**
 * ============================================================
 * Photopea No Ads Panel — background.js
 * ============================================================
 *
 * WHAT THIS FILE DOES
 * -------------------
 * When Photopea loads, the browser fetches:
 *
 *     https://www.photopea.com/code/pp/pp<timestamp>.js
 *
 * Inside that file there is a layout function:
 *
 *     cT.prototype.Sr
 *
 * That function normally:
 *   1. Reserves 320px of width for advertising.
 *   2. Appends the ad panel to the right side.
 *   3. Loads ad scripts/iframes.
 *
 * This extension intercepts that JS file BEFORE the browser runs it
 * and rewrites a single line:
 *
 *     var K=eb.U$,D=!this.rX||...;   →   var K=eb.U$,D=!0;
 *
 * With D=true Photopea goes into "no ads" mode:
 *   - no 320px width cut,
 *   - no ad panel in the DOM,
 *   - no ad scripts/iframes loaded.
 *
 * WHY NOT SHIP A PATCHED COPY OF THE FILE?
 * ----------------------------------------
 * The `pp` filename changes on every Photopea update. A bundled copy
 * would go stale. Instead we use Firefox's
 * `webRequest.filterResponseData` API to patch the response in flight.
 * The URL pattern `/code/pp/*` matches any future filename.
 *
 * DATA FLOW (short version):
 * --------------------------
 * 1. Browser requests `pp*.js`.
 * 2. `onBeforeRequest` sees the request.
 * 3. `filterResponseData` opens a filter on the response.
 * 4. `ondata` → buffer incoming chunks.
 * 5. `onstop` → join chunks and apply the patch.
 * 6. `write`  → hand the patched content to the browser.
 * 7. `close`  → finish the response.
 * ============================================================
 */

// Common prefix for all console logs so logs from this extension
// are easy to spot in the browser console.
const LOG_PREFIX = "[Photopea No-Ads]";

// Which URLs should be intercepted. The `*` wildcard matches the
// timestamp/hash part of Photopea's script filenames.
const PHOTOPEA_SCRIPT_URL_PATTERNS = [
  "*://photopea.com/code/pp/*",
  "*://*.photopea.com/code/pp/*"
];

/**
 * WHY CAPTURE GROUPS?
 * -------------------
 * Photopea's JS is minified. Names like `K`, `D`, `C` are not meaningful;
 * they were generated by the minifier and may change on the next build.
 *
 * `([A-Za-z_$][\w$]*)` means "any valid variable name".
 * We store it in a capture group and reuse it as `$1` / `$2` in the
 * replacement, so the patch survives simple variable renames.
 */


// PRIMARY PATTERN:
// Matches `var K=eb.U$,D=...;` and keeps both variable names intact.
const AD_BRANCH_PATTERN =
  /var ([A-Za-z_$][\w$]*)=eb\.U\$,([A-Za-z_$][\w$]*)=[^;]+;/;

// Replacement strings for the patterns above.
// `$1` / `$2` write back whatever variable names were captured.
const AD_BRANCH_REPLACEMENT = "var $1=eb.U$,$2=!0;";


// FALLBACK PATTERN:
// If the primary pattern fails, matches `D=!this.rX||...;`.
const AD_BRANCH_FALLBACK_PATTERN =
  /([A-Za-z_$][\w$]*)=!this\.rX\|\|[^;]+;/;

const AD_BRANCH_FALLBACK_REPLACEMENT = "$1=!0;";



// LAST-RESORT PATTERN:
// Matches the width-reservation logic:
// `else{if(K==0)l-=84;else C-=K==1?180:320}`.
// The `\1` backreference guarantees that the variable used in `K==0`
// is the same one used later in `K==1?180:320`.
const AD_SPACE_RESERVATION_PATTERN =
  /else\{if\(([A-Za-z_$][\w$]*)==0\)([A-Za-z_$][\w$]*)-=84;else ([A-Za-z_$][\w$]*)-=\1==1\?180:320\}/;

const AD_SPACE_RESERVATION_REPLACEMENT = "else{}";





/**
 * Takes Photopea's minified JS source and disables the ad branch.
 *
 * @param {string} originalSource - The original JS text from Photopea.
 * @returns {{ patchedSource: string, didPatch: boolean }}
 *          patchedSource: the (possibly) patched source.
 *          didPatch: true if any pattern was applied.
 */
function patchPhotopeaSource(originalSource) {
  // Keep the patched text separate. If no pattern matches, we return
  // the original source unchanged (fail-open behaviour).
  let patchedSource = originalSource;
  let didPatch = false;

  // 1) Primary: `var K=eb.U$,D=...;` → `var K=eb.U$,D=!0;`
  if (AD_BRANCH_PATTERN.test(patchedSource)) {
    patchedSource = patchedSource.replace(
      AD_BRANCH_PATTERN,
      AD_BRANCH_REPLACEMENT
    );
    didPatch = true;
    console.log(`${LOG_PREFIX} Ad branch disabled`);
  }
  // 2) Fallback: `D=!this.rX||...;` → `D=!0;`
  else if (AD_BRANCH_FALLBACK_PATTERN.test(patchedSource)) {
    patchedSource = patchedSource.replace(
      AD_BRANCH_FALLBACK_PATTERN,
      AD_BRANCH_FALLBACK_REPLACEMENT
    );
    didPatch = true;
    console.log(`${LOG_PREFIX} Ad branch disabled (fallback)`);
  }
  // If neither matched, warn but leave the source untouched so Photopea
  // still works (the CSS fallback can still hide the panel).
  else {
    console.warn(`${LOG_PREFIX} Ad branch pattern not found`);
  }

  // 3) Remove the width-reservation line as an extra safety net.
  //    If D was disabled above, this line is dead code anyway.
  if (AD_SPACE_RESERVATION_PATTERN.test(patchedSource)) {
    patchedSource = patchedSource.replace(
      AD_SPACE_RESERVATION_PATTERN,
      AD_SPACE_RESERVATION_REPLACEMENT
    );
    didPatch = true;
    console.log(`${LOG_PREFIX} Ad width reservation removed`);
  }

  return { patchedSource, didPatch };
}

/**
 * ============================================================
 * WEBREQUEST LISTENER
 * ============================================================
 * Runs whenever the browser requests a `code/pp/*` script.
 */
browser.webRequest.onBeforeRequest.addListener(
  (requestDetails) => {
    // Open a filter on the response before the browser receives it.
    // This must be called synchronously inside the listener.
    const responseFilter = browser.webRequest.filterResponseData(
      requestDetails.requestId
    );

    // Helpers for converting bytes <-> text.
    const textDecoder = new TextDecoder("utf-8");
    const textEncoder = new TextEncoder();

    // Incoming response chunks are buffered here.
    const responseChunks = [];

    // `ondata`: called for every chunk of the response body.
    // `{ stream: true }` lets the decoder handle multi-byte UTF-8
    // characters that may be split across chunk boundaries.
    responseFilter.ondata = (dataEvent) => {
      responseChunks.push(
        textDecoder.decode(dataEvent.data, { stream: true })
      );
    };

    // If something goes wrong, try to close the filter cleanly.
    responseFilter.onerror = () => {
      console.error(
        `${LOG_PREFIX} Response filter error:`,
        responseFilter.error
      );
      try {
        responseFilter.close();
      } catch (closeError) {
        // Ignore close errors; the request is already broken.
      }
    };

    // `onstop`: called when the full response has arrived.
    responseFilter.onstop = () => {
      // Flush the decoder to get any remaining buffered text.
      responseChunks.push(textDecoder.decode());

      // Join all chunks into the original JS source text.
      const originalSource = responseChunks.join("");

      // Apply the patch.
      const { patchedSource, didPatch } =
        patchPhotopeaSource(originalSource);

      if (didPatch) {
        console.log(`${LOG_PREFIX} Patched:`, requestDetails.url);
      } else {
        console.warn(`${LOG_PREFIX} Unchanged:`, requestDetails.url);
      }

      // Convert the patched text back to bytes and hand it to the browser.
      responseFilter.write(textEncoder.encode(patchedSource));

      // Close the response. Forgetting this would hang the request.
      responseFilter.close();
    };

    // Returning `{}` means "don't cancel the request; I'm taking over
    // the response".
    return {};
  },
  {
    // Only intercept these URLs.
    urls: PHOTOPEA_SCRIPT_URL_PATTERNS,
    // Only intercept script loads.
    types: ["script"]
  },
  // `blocking` is required to modify the response.
  ["blocking"]
);
